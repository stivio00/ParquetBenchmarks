#!/usr/bin/env python3
"""Parquet read/write benchmarks in Python, mirroring the C# suite in ../.

Engines: pandas (pyarrow and fastparquet engines), polars, pyarrow, duckdb.
Dataset: 1M rows x 10 columns (see generate_dataset); every writer pins Snappy
compression so the output files are comparable.

Run:
    uv run python benchmark.py             # full suite, 1M rows
    uv run python benchmark.py --quick     # 100k rows smoke run
    uv run python benchmark.py --filter polars
"""

from __future__ import annotations

import argparse
import gc
import platform
import random
import shutil
import statistics
import tempfile
import time
import uuid
from datetime import datetime, timedelta
from pathlib import Path

import duckdb
import fastparquet
import pandas as pd
import polars as pl
import pyarrow as pa
import pyarrow.parquet as pq

# Same value pools as the C# DataGenerator.
CATEGORIES = ["Electronics", "Groceries", "Apparel", "Automotive", "Books", "Toys", "Garden", "Sports"]
ADJECTIVES = ["Rapid", "Silent", "Golden", "Crimson", "Frozen", "Ancient", "Electric", "Hollow", "Vivid", "Quiet"]
NOUNS = ["Falcon", "Reactor", "Meadow", "Circuit", "Harbor", "Lantern", "Comet", "Anvil", "Glacier", "Orchid"]

SELECT_COLUMNS = (
    "Id, Name, Price, CreatedAt, CreatedAtText, IsActive, "
    "Category, Rating, ExternalId, Description"
)

BASELINES = {
    "write": "Pandas_PyArrow_Write",
    "read": "Pandas_PyArrow_ReadDecode",
    "shared": "SharedFile_Pandas_ReadDecode",
}

# The SharedFile_* benchmarks decode data/bench-1m.parquet — the canonical
# reference file generated by make_reference.py and kept in the repo so the
# C# suite (SharedFileReadBenchmarks) and this suite read identical bytes.
SHARED_FILE = Path(__file__).resolve().parent.parent / "data" / "bench-1m.parquet"

BENCHMARK_NAMES = (
    "Pandas_PyArrow_Write",
    "Pandas_Fastparquet_Write",
    "Polars_Write",
    "PyArrow_Write",
    "DuckDb_Write",
    "Pandas_PyArrow_ReadDecode",
    "Pandas_Fastparquet_ReadDecode",
    "Polars_ReadDecode",
    "PyArrow_ReadDecode",
    "DuckDb_FetchAll_ReadDecode",
    "SharedFile_Polars_ReadDecode",
    "SharedFile_PyArrow_ReadDecode",
    "SharedFile_Pandas_ReadDecode",
    "SharedFile_DuckDb_FetchAll_ReadDecode",
)


def generate_dataset(n_rows: int, seed: int = 42) -> pd.DataFrame:
    """Mirrors the C# DataGenerator: same columns, value ranges and string
    patterns. The RNG differs (C# Random vs Python's Mersenne Twister), so the
    data is shape-identical, not byte-identical, to the C# dataset."""
    rng = random.Random(seed)
    base = datetime(2020, 1, 1)
    minute_span = 60 * 24 * 365 * 5

    ids: list[int] = []
    names: list[str] = []
    prices: list[float] = []
    created: list[datetime] = []
    created_text: list[str] = []
    is_active: list[bool] = []
    categories: list[str] = []
    ratings: list[float] = []
    external_ids: list[str] = []
    descriptions: list[str] = []

    for i in range(n_rows):
        ts = base + timedelta(minutes=rng.randrange(minute_span))
        ids.append(i + 1)
        names.append(f"{rng.choice(ADJECTIVES)} {rng.choice(NOUNS)} #{i}")
        prices.append(round(rng.random() * 999.99, 2))
        created.append(ts)
        created_text.append(ts.strftime("%Y-%m-%dT%H:%M:%S"))
        is_active.append(rng.randrange(2) == 1)
        categories.append(rng.choice(CATEGORIES))
        ratings.append(round(rng.random() * 5.0, 3))
        # Seeded GUID so the whole dataset stays reproducible.
        external_ids.append(str(uuid.UUID(int=rng.getrandbits(128))))
        parts = [f"Record {i}:"]
        for _ in range(rng.randrange(12, 36)):
            parts.append(rng.choice(ADJECTIVES))
            parts.append(rng.choice(NOUNS))
        descriptions.append(" ".join(parts))

    df = pd.DataFrame(
        {
            "Id": ids,
            "Name": names,
            "Price": prices,
            "CreatedAt": created,
            "CreatedAtText": created_text,
            "IsActive": is_active,
            "Category": categories,
            "Rating": ratings,
            "ExternalId": external_ids,
            "Description": descriptions,
        }
    )
    return df.astype(
        {
            "Id": "int64",
            "Price": "float32",
            "CreatedAt": "datetime64[ns]",
            "IsActive": "bool",
            "Rating": "float64",
        }
    )


def duckdb_write(source: pa.Table, out_path: Path) -> None:
    """Mirror of the C# DuckDb_Write: land rows in an in-memory table, then
    COPY out to parquet (DuckDB's default codec is Snappy)."""
    con = duckdb.connect(":memory:")
    try:
        con.register("src", source)
        con.execute("CREATE TABLE bench AS SELECT * FROM src")
        con.execute(f"COPY bench TO '{out_path}' (FORMAT parquet)")
    finally:
        con.close()


def duckdb_read_all(path: Path) -> int:
    """Mirror of the C# DuckDb_AdoNet_ReadDecode: fresh in-memory connection,
    read_parquet, full row-by-row materialization (fetchall -> list of tuples)."""
    con = duckdb.connect(":memory:")
    try:
        rows = con.execute(f"SELECT {SELECT_COLUMNS} FROM read_parquet('{path}')").fetchall()
        return len(rows)
    finally:
        con.close()


def measure(fn, warmup: int, iterations: int) -> list[float]:
    for _ in range(warmup):
        fn()
    samples: list[float] = []
    for _ in range(iterations):
        gc.collect()  # outside the timed region, so runs stay comparable
        start = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - start)
    return samples


def human_size(num_bytes: int) -> str:
    value = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024 or unit == "GB":
            return f"{value:,.1f} {unit}"
        value /= 1024
    return f"{value:,.1f} GB"


def fmt_ms(seconds: float) -> str:
    return f"{seconds * 1000.0:,.1f} ms"


def print_report(results: dict[str, list[tuple[str, list[float]]]], n_rows: int) -> None:
    for group in ("write", "read", "shared"):
        rows = results.get(group)
        if not rows:
            continue
        baseline_name = BASELINES[group]
        baseline_mean = next(
            (statistics.mean(s) for n, s in rows if n == baseline_name), None
        )
        width = max(len(name) for name, _ in rows) + 2
        if group == "write":
            title = f"Write {n_rows:,} rows"
        elif group == "read":
            title = f"Read + decode ({n_rows:,} rows)"
        else:
            title = "Read + decode - shared reference file (data/bench-1m.parquet)"
        print(f"\n{title}:")
        print(f"| {'Benchmark':<{width}} | {'Mean':>12} | {'Min':>12} | {'Max':>12} | {'StdDev':>10} | {'Ratio':>7} |")
        print(f"|{'-' * (width + 2)}|{'-' * 14}|{'-' * 14}|{'-' * 14}|{'-' * 12}|{'-' * 9}|")
        for name, samples in rows:
            mean = statistics.mean(samples)
            std = statistics.stdev(samples) if len(samples) > 1 else 0.0
            ratio = f"{mean / baseline_mean:.2f}x" if baseline_mean else "-"
            print(
                f"| {name:<{width}} | {fmt_ms(mean):>12} | {fmt_ms(min(samples)):>12} "
                f"| {fmt_ms(max(samples)):>12} | {fmt_ms(std):>10} | {ratio:>7} |"
            )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Parquet read/write benchmarks (pandas, polars, pyarrow, fastparquet, duckdb)",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--rows", type=int, default=1_000_000, help="row count")
    parser.add_argument("--warmup", type=int, default=2)
    parser.add_argument("--iterations", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--filter", default="", help="case-insensitive substring; only matching benchmarks run")
    parser.add_argument("--quick", action="store_true", help="smoke run: 100k rows, 1 warmup, 3 iterations")
    parser.add_argument("--list", action="store_true", help="list benchmark names and exit")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.quick:
        args.rows, args.warmup, args.iterations = 100_000, 1, 3

    if args.list:
        print("\n".join(BENCHMARK_NAMES))
        return 0

    print(
        f"Python {platform.python_version()} | pandas {pd.__version__} | "
        f"polars {pl.__version__} | pyarrow {pa.__version__} | "
        f"duckdb {duckdb.__version__} | fastparquet {fastparquet.__version__}"
    )
    print(f"Generating {args.rows:,} rows (seed {args.seed}) ...")

    tmp = Path(tempfile.mkdtemp(prefix="parquet-bench-py-"))
    try:
        # Canonical dataset is a pandas DataFrame (the Python lingua franca);
        # the polars and Arrow forms are derived once, unmeasured, via
        # near-zero-copy conversions. Each writer then starts from its own
        # native representation.
        df = generate_dataset(args.rows, args.seed)
        pl_df = pl.from_pandas(df)
        arrow_table = pa.Table.from_pandas(df, preserve_index=False)

        read_dir = tmp / "read"
        write_dir = tmp / "write"
        read_dir.mkdir()
        write_dir.mkdir()
        read_paths = {
            "pandas_pa": read_dir / "pandas_pa.parquet",
            "pandas_fp": read_dir / "pandas_fp.parquet",
            "polars": read_dir / "polars.parquet",
            "pyarrow": read_dir / "pyarrow.parquet",
            "duckdb": read_dir / "duckdb.parquet",
        }
        write_paths = {k: write_dir / f"{k}.parquet" for k in read_paths}

        writers = {
            "pandas_pa": lambda p: df.to_parquet(p, engine="pyarrow", compression="snappy"),
            "pandas_fp": lambda p: df.to_parquet(p, engine="fastparquet", compression="snappy"),
            "polars": lambda p: pl_df.write_parquet(p, compression="snappy"),
            "pyarrow": lambda p: pq.write_table(arrow_table, p, compression="snappy"),
            "duckdb": lambda p: duckdb_write(arrow_table, p),
        }
        readers = {
            "pandas_pa": lambda p: pd.read_parquet(p, engine="pyarrow"),
            "pandas_fp": lambda p: pd.read_parquet(p, engine="fastparquet"),
            "polars": lambda p: pl.read_parquet(p),
            "pyarrow": lambda p: pq.read_table(p),
            "duckdb": lambda p: duckdb_read_all(p),
        }

        # Setup: each engine's file is written exactly once, unmeasured, so
        # every read benchmark measures pure read + decode of its own file.
        print("Writing setup files (unmeasured) ...")
        for key, write in writers.items():
            write(read_paths[key])
        for path in sorted(read_paths.values()):
            print(f"  {path.name:<18} {human_size(path.stat().st_size)}")

        benchmarks = [
            ("write", "Pandas_PyArrow_Write", lambda: writers["pandas_pa"](write_paths["pandas_pa"])),
            ("write", "Pandas_Fastparquet_Write", lambda: writers["pandas_fp"](write_paths["pandas_fp"])),
            ("write", "Polars_Write", lambda: writers["polars"](write_paths["polars"])),
            ("write", "PyArrow_Write", lambda: writers["pyarrow"](write_paths["pyarrow"])),
            ("write", "DuckDb_Write", lambda: writers["duckdb"](write_paths["duckdb"])),
            ("read", "Pandas_PyArrow_ReadDecode", lambda: readers["pandas_pa"](read_paths["pandas_pa"])),
            ("read", "Pandas_Fastparquet_ReadDecode", lambda: readers["pandas_fp"](read_paths["pandas_fp"])),
            ("read", "Polars_ReadDecode", lambda: readers["polars"](read_paths["polars"])),
            ("read", "PyArrow_ReadDecode", lambda: readers["pyarrow"](read_paths["pyarrow"])),
            ("read", "DuckDb_FetchAll_ReadDecode", lambda: readers["duckdb"](read_paths["duckdb"])),
        ]

        # Cross-language group: decode the shared reference file so the C#
        # SharedFileReadBenchmarks and these numbers come from identical bytes.
        if SHARED_FILE.exists():
            benchmarks += [
                ("shared", "SharedFile_Polars_ReadDecode", lambda: pl.read_parquet(SHARED_FILE)),
                ("shared", "SharedFile_PyArrow_ReadDecode", lambda: pq.read_table(SHARED_FILE)),
                ("shared", "SharedFile_Pandas_ReadDecode", lambda: pd.read_parquet(SHARED_FILE, engine="pyarrow")),
                ("shared", "SharedFile_DuckDb_FetchAll_ReadDecode", lambda: duckdb_read_all(SHARED_FILE)),
            ]
        else:
            print(
                "data/bench-1m.parquet not found - skipping SharedFile_* benchmarks "
                "(generate it with: uv run python make_reference.py)"
            )

        selected = [b for b in benchmarks if args.filter.lower() in b[1].lower()]
        if not selected:
            print(f"No benchmark matches --filter '{args.filter}'. Use --list to see names.")
            return 1

        print(f"\nRunning {len(selected)} benchmark(s): warmup {args.warmup}, iterations {args.iterations}\n")
        results: dict[str, list[tuple[str, list[float]]]] = {}
        for group, name, fn in selected:
            print(f"  {name} ...", flush=True)
            results.setdefault(group, []).append((name, measure(fn, args.warmup, args.iterations)))

        print_report(results, args.rows)
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
